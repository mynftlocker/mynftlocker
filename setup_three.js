"            <LockerFrame",
"              card={card}",
"              isFlipped={flippedSlug===card.slug}",
"              isStarred={hof.includes(card.slug)}",
"              onFlip={onFlip}",
"              onStar={onStar}",
"            />",
"          </Html>",
"        ))}",
"      </Canvas>",
