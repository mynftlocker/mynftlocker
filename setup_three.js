"// ── SPOT PAR CASIER ──────────────────────────────",
"function Spot({x}:{x:number}){",
"  const {scene}=useThree();",
"  const ref=useRef<THREE.SpotLight>(null!);",
"  useEffect(()=>{",
"    const t=new THREE.Object3D();",
"    t.position.set(x,-1,-2.8);",
"    scene.add(t);",
"    if(ref.current) ref.current.target=t;",
"    return ()=>{scene.remove(t);};",
"  },[x,scene]);",
"  return <spotLight ref={ref} position={[x,4.5,0.5]} angle={0.3} penumbra={0.6} intensity={160} color='#ffc870' distance={12}/>;",
"}",
"",
